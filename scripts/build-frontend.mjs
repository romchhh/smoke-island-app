#!/usr/bin/env node
/**
 * Concatenate frontend/js/*.js into frontend/app.js for a single-request production bundle.
 * Source of truth remains the modular files; run this before deploy / after JS edits.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../frontend');
const jsDir = path.join(root, 'js');

const ORDER = [
  'icons.js',
  'state.js',
  'api.js',
  'layout.js',
  'pages-shop.js',
  'pages-account.js',
  'mobile.js',
  'support.js',
  'bonus-ui.js',
  'pages-order.js',
  'render.js',
  'events.js',
  'session.js',
  'boot.js',
];

const stripHeader = (text) =>
  text
    .replace(/^'use strict';\s*/m, '')
    .replace(/^\/\* =+\n[\s\S]*?=+ \*\/\s*/m, '');

const parts = ORDER.map((name) => {
  const file = path.join(jsDir, name);
  if (!fs.existsSync(file)) throw new Error(`Missing module: ${name}`);
  return `\n/* —— ${name} —— */\n${stripHeader(fs.readFileSync(file, 'utf8')).trim()}\n`;
});

const banner = `/* Smoke Island storefront — built from frontend/js/*
 * Do not edit this file by hand. Change modules in frontend/js/ then run:
 *   node scripts/build-frontend.mjs
 */
'use strict';
`;

const out = path.join(root, 'app.js');
fs.writeFileSync(out, banner + parts.join('\n'));
console.log(`Built ${path.relative(process.cwd(), out)} (${fs.statSync(out).size} bytes, ${ORDER.length} modules)`);
